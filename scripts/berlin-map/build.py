KEYS = {  # Bezirk name -> (key, short)
    "Pankow": ("pankow", "Pankow"), "Lichtenberg": ("lichtenberg", "L'berg"),
    "Marzahn-Hellersdorf": ("marzahn-hellersdorf", "Marzahn"), "Treptow-Köpenick": ("treptow-koepenick", "Treptow"),
    "Reinickendorf": ("reinickendorf", "R'dorf"), "Spandau": ("spandau", "Spandau"),
    "Charlottenburg-Wilmersdorf": ("charlottenburg-wilmersdorf", "Charl."),
    "Steglitz-Zehlendorf": ("steglitz-zehlendorf", "Steglitz"),
    "Tempelhof-Schöneberg": ("tempelhof-schoeneberg", "T'hof"), "Neukölln": ("neukoelln", "N'kölln"),
}
# Hand-nudged label centres (viewBox units) where the centroid labels collide in the crowded centre.
LABELS = {"mitte": (183, 143), "friedrichshain": (228, 166), "kreuzberg": (188, 178), "lichtenberg": (240, 128),
          "tempelhof-schoeneberg": (172, 222), "neukoelln": (232, 230), "marzahn-hellersdorf": (298, 152)}
EAST = {"Pankow", "Lichtenberg", "Marzahn-Hellersdorf", "Treptow-Köpenick"}
GROUPS = [  # name, key, short, side, Ortsteile
    ("Mitte", "mitte", "Mitte", "east", {"Mitte"}),
    ("Wedding/Tiergarten", "wedding-tiergarten", "Wedding", "west",
     {"Moabit", "Hansaviertel", "Tiergarten", "Wedding", "Gesundbrunnen"}),
    ("Friedrichshain", "friedrichshain", "F'hain", "east", {"Friedrichshain"}),
    ("Kreuzberg", "kreuzberg", "X'berg", "west", {"Kreuzberg"}),
]


def dp(pts, eps):
    if len(pts) < 3:
        return pts
    (x1, y1), (x2, y2) = pts[0], pts[-1]
    dx, dy = x2 - x1, y2 - y1
    L = math.hypot(dx, dy) or 1e-12
    i, m = 0, 0
    for k in range(1, len(pts) - 1):
        x, y = pts[k]
        d = abs(dy * x - dx * y + x2 * y1 - y2 * x1) / L
        if d > m:
            i, m = k, d
    return dp(pts[: i + 1], eps)[:-1] + dp(pts[i:], eps) if m > eps else [pts[0], pts[-1]]


def centroid(r):
    a = cx = cy = 0.0
    for (x1, y1), (x2, y2) in zip(r, r[1:] + r[:1]):
        k = x1 * y2 - x2 * y1
        a += k; cx += (x1 + x2) * k; cy += (y1 + y2) * k
    return (cx / (3 * a), cy / (3 * a), abs(a) / 2) if a else (r[0][0], r[0][1], 0)


def inside(x, y, r):
    c = False
    for (x1, y1), (x2, y2) in zip(r, r[1:] + r[:1]):
        if (y1 > y) != (y2 > y) and x < (x2 - x1) * (y - y1) / (y2 - y1) + x1:
            c = not c
    return c


def label_point(r):
    cx, cy, _ = centroid(r)
    if inside(cx, cy, r):
        return cx, cy
    xs, ys = [p[0] for p in r], [p[1] for p in r]  # concave: nearest interior grid point to the centroid
    cands = [(x, y) for x in range(int(min(xs)), int(max(xs)) + 1, 2) for y in range(int(min(ys)), int(max(ys)) + 1, 2)
             if inside(x, y, r)]
    return min(cands, key=lambda p: (p[0] - cx) ** 2 + (p[1] - cy) ** 2)


bz = json.load(open(sys.argv[1]))
ot = json.load(open(sys.argv[2]))
c = math.cos(math.radians(52.5))


def rings(f):
    g = f["geometry"]
    polys = g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]
    return [[(x * c, -y) for x, y, *_ in p[0]] for p in polys]


allp = [p for f in bz["features"] for r in rings(f) for p in r]
minx, maxx = min(p[0] for p in allp), max(p[0] for p in allp)
miny, maxy = min(p[1] for p in allp), max(p[1] for p in allp)
W = 400
s = W / (maxx - minx)
H = round((maxy - miny) * s)


def build(rs):
    d, best = "", None
    for r in rs:
        pts = [((x - minx) * s, (y - miny) * s) for x, y in r]
        h = len(pts) // 2
        sp = dp(pts[: h + 1], 0.8)[:-1] + dp(pts[h:], 0.8)
        if len(sp) < 4:
            continue
        d += "M" + "L".join(f"{x:.1f},{y:.1f}" for x, y in sp) + "Z"
        if best is None or centroid(sp)[2] > centroid(best)[2]:
            best = sp
    lx, ly = label_point(best)
    return d, round(lx), round(ly)


def place(key, d, lx, ly):
    return (d, *LABELS.get(key, (lx, ly)))


areas = []
for f in bz["features"]:
    n = f["properties"]["Gemeinde_name"]
    if n in KEYS:
        key, short = KEYS[n]
        areas.append((n, key, short, "east" if n in EAST else "west", *place(key, *build(rings(f)))))
for name, key, short, side, names in GROUPS:
    rs = [r for f in ot["features"] if f["properties"]["OTEIL"] in names
          and f["properties"]["BEZIRK"] in ("Mitte", "Friedrichshain-Kreuzberg") for r in rings(f)]
    assert rs, name
    areas.append((name, key, short, side, *place(key, *build(rs))))
assert len(areas) == 14

print(HEADER)
print(f'export const MAP_VIEWBOX = "-24 -24 {W + 48} {H + 48}";\n')
print("export const BERLIN_AREAS: ReadonlyArray<{")
print('  key: Exclude<Area, "brandenburg" | "elsewhere">;\n  name: string;\n  short: string;\n  side: "east" | "west";')
print("  d: string;\n  labelX: number;\n  labelY: number;\n}> = [")
for name, key, short, side, d, lx, ly in areas:
    print(f'  {{ d: "{d}", key: "{key}", labelX: {lx}, labelY: {ly}, name: "{name}", short: "{short}", side: "{side}" }},')
print("];")
