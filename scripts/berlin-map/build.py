"""One-off: Bezirke GeoJSON (the 12 current Bezirke) -> website/src/data/berlinAreas.ts (not run at build time).

Usage: python3 -I scripts/berlin-map/build.py <bezirke.geojson> > website/src/data/berlinAreas.ts
Sources and licence: see HEADER below.
"""
import json, math, sys

sys.setrecursionlimit(10000)

HEADER = """// Generated by scripts/berlin-map/build.py - do not edit by hand.
// Sources (Geoportal Berlin / ALKIS Berlin, via the Technologiestiftung open-data bucket):
//   https://tsb-opendata.s3.eu-central-1.amazonaws.com/bezirksgrenzen/bezirksgrenzen.geojson
// Licence: "ALKIS Berlin Bezirke" is Datenlizenz Deutschland - Zero - 2.0 (dl-de-zero-2.0, no attribution needed,
//   https://daten.berlin.de/datensaetze/alkis-berlin-bezirke-wfs-ced31d7d). We still credit it under the map.
// Geometry simplified (Douglas-Peucker) and projected equirectangular at 52.5 deg N.
import type { Area } from "payload-app/word-feedback";
"""

KEYS = {  # Bezirk name -> (key, label); "|" in a label breaks the line
    "Mitte": ("mitte", "Mitte"), "Friedrichshain-Kreuzberg": ("friedrichshain-kreuzberg", "Friedrichshain-|Kreuzberg"),
    "Pankow": ("pankow", "Pankow"), "Lichtenberg": ("lichtenberg", "Lichtenberg"),
    "Marzahn-Hellersdorf": ("marzahn-hellersdorf", "Marzahn-|Hellersdorf"), "Treptow-Köpenick": ("treptow-koepenick", "Treptow-|Köpenick"),
    "Reinickendorf": ("reinickendorf", "Reinickendorf"), "Spandau": ("spandau", "Spandau"),
    "Charlottenburg-Wilmersdorf": ("charlottenburg-wilmersdorf", "Charlottenburg-|Wilmersdorf"),
    "Steglitz-Zehlendorf": ("steglitz-zehlendorf", "Steglitz-|Zehlendorf"),
    "Tempelhof-Schöneberg": ("tempelhof-schoeneberg", "Tempelhof-|Schöneberg"), "Neukölln": ("neukoelln", "Neukölln"),
}
# Hand-placed label centres (viewBox units), only where the computed point sits badly. Empty = computed.
LABELS = {}


def dp(pts, eps):
    if len(pts) < 3:
        return pts
    (x1, y1), (x2, y2) = pts[0], pts[-1]
    dx, dy = x2 - x1, y2 - y1
    L = math.hypot(dx, dy) or 1e-12
    i, m = 0, 0
    for k in range(1, len(pts) - 1):
        x, y = pts[k]
        d = abs(dy * x - dx * y + x2 * y1 - y2 * x1) / L
        if d > m:
            i, m = k, d
    return dp(pts[: i + 1], eps)[:-1] + dp(pts[i:], eps) if m > eps else [pts[0], pts[-1]]


def centroid(r):
    a = cx = cy = 0.0
    for (x1, y1), (x2, y2) in zip(r, r[1:] + r[:1]):
        k = x1 * y2 - x2 * y1
        a += k; cx += (x1 + x2) * k; cy += (y1 + y2) * k
    return (cx / (3 * a), cy / (3 * a), abs(a) / 2) if a else (r[0][0], r[0][1], 0)


def inside(x, y, r):
    c = False
    for (x1, y1), (x2, y2) in zip(r, r[1:] + r[:1]):
        if (y1 > y) != (y2 > y) and x < (x2 - x1) * (y - y1) / (y2 - y1) + x1:
            c = not c
    return c


def label_point(r):
    cx, cy, _ = centroid(r)
    if inside(cx, cy, r):
        return cx, cy
    xs, ys = [p[0] for p in r], [p[1] for p in r]  # concave: nearest interior grid point to the centroid
    cands = [(x, y) for x in range(int(min(xs)), int(max(xs)) + 1, 2) for y in range(int(min(ys)), int(max(ys)) + 1, 2)
             if inside(x, y, r)]
    return min(cands, key=lambda p: (p[0] - cx) ** 2 + (p[1] - cy) ** 2)


bz = json.load(open(sys.argv[1]))
c = math.cos(math.radians(52.5))


def rings(f):
    g = f["geometry"]
    polys = g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]
    return [[(x * c, -y) for x, y, *_ in p[0]] for p in polys]


allp = [p for f in bz["features"] for r in rings(f) for p in r]
minx, maxx = min(p[0] for p in allp), max(p[0] for p in allp)
miny, maxy = min(p[1] for p in allp), max(p[1] for p in allp)
W = 400
s = W / (maxx - minx)
H = round((maxy - miny) * s)


def build(rs):
    d, best = "", None
    for r in rs:
        pts = [((x - minx) * s, (y - miny) * s) for x, y in r]
        h = len(pts) // 2
        sp = dp(pts[: h + 1], 0.8)[:-1] + dp(pts[h:], 0.8)
        if len(sp) < 4:
            continue
        d += "M" + "L".join(f"{x:.1f},{y:.1f}" for x, y in sp) + "Z"
        if best is None or centroid(sp)[2] > centroid(best)[2]:
            best = sp
    lx, ly = label_point(best)
    return d, round(lx), round(ly)


def place(key, d, lx, ly):
    return (d, *LABELS.get(key, (lx, ly)))


areas = []
for f in bz["features"]:
    n = f["properties"]["Gemeinde_name"]
    key, short = KEYS[n]
    areas.append((n, key, short, *place(key, *build(rings(f)))))
assert len(areas) == 12

print(HEADER)
print(f"export const MAP_W = {W};\nexport const MAP_H = {H};")
print(f'export const MAP_VIEWBOX = "-24 -24 {W + 48} {H + 48}";\n')
print("export const BERLIN_AREAS: ReadonlyArray<{")
print('  key: Exclude<Area, "brandenburg" | "elsewhere">;\n  name: string;\n  short: string;')
print("  d: string;\n  labelX: number;\n  labelY: number;\n}> = [")
for name, key, short, d, lx, ly in areas:
    print(f'  {{\n    d: "{d}",\n    key: "{key}",\n    labelX: {lx},\n    labelY: {ly},\n    name: "{name}",\n    short: "{short}",\n  }},')
print("];")
