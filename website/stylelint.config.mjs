import { readFileSync } from "node:fs";

import legacyFiles from "./stylelint.legacy-files.mjs";

// Design-system gate (spec §11). Banned in `var()` of a strict file: the old palette, every
// legacy alias (those that are not a current token) and the primitive colour tier.
const read = (path) => readFileSync(new URL(path, import.meta.url), "utf8");
const names = (css) => [...css.matchAll(/^\s*(--[\w-]+):/gm)].map((m) => m[1]);
const current = new Set(names(read("./src/styles/tokens/_tokens.generated.scss")));
const legacyAliases = names(read("./src/styles/tokens/_legacy-aliases.scss")).filter(
  (name) => !current.has(name),
);
const bannedVar = new RegExp(
  `var\\(\\s*(?:${legacyAliases.join("|")}|--(?:orange|blue|new-blue|white|grey|red|yellow)(?:-\\w+)?` +
    `|--color-(?:white|black|orange|red|cream|grey|ink)-[\\w-]+|--color-(?:danger|success|gold))\\s*[,)]`,
);

// A raw length or duration: number with unit, not part of a name such as --space-2.
const num = String.raw`(?:^|[^\w.-])-?\d*\.?\d+`;
const rawLength = new RegExp(
  `${num}(?:px|r?em|ch|ex|pt|%|[sld]?v(?:h|w|min|max)|cq(?:w|h|i|b|min|max))`,
);
const rawTime = new RegExp(`${num}m?s(?!\\w)`);
// The whole value must be tokens (a comma list of var()) or a keyword.
const notToken = /^(?!(?:var\([^()]*\)(?:\s*,\s*var\([^()]*\))*|none|inherit|initial|unset)$)/;

const strictRules = {
  "color-no-hex": true,
  "color-named": "never",
  "function-disallowed-list": [
    "rgb",
    "rgba",
    "hsl",
    "hsla",
    "hwb",
    "lab",
    "lch",
    "oklab",
    "oklch",
    "color-mix",
    "color",
  ],
  // `--_` custom properties are never matched by a property key, so raw lengths stay legal there.
  "declaration-property-value-disallowed-list": {
    "/.*/": [bannedVar, /\$|#\{/],
    "font-size": [rawLength],
    "/^(margin|padding|scroll-margin|scroll-padding)(-(block|inline)(-(start|end))?)?$|^(row-|column-)?gap$|^inset(-block|-inline)?(-(start|end))?$/":
      [rawLength],
    "/^border(-(start|end)-(start|end))?-radius$/": [rawLength],
    "/^(box|text)-shadow$/": [notToken],
    "z-index": [/^-?\d+$/],
    "/^(transition|animation)(-duration|-delay)?$/": [rawTime],
    "/^font(-family)?$/": [notToken],
  },
  "property-disallowed-list": [
    "width",
    "height",
    "min-width",
    "min-height",
    "max-width",
    "max-height",
    "top",
    "right",
    "bottom",
    "left",
    "/^(margin|padding|scroll-margin|scroll-padding)-(top|right|bottom|left)$/",
    "/^border-(top|right|bottom|left)(-(width|color|style))?$/",
    "/^border-(top|bottom)-(left|right)-radius$/",
  ],
  "at-rule-disallowed-list": ["media", "import", "extend"],
  "selector-class-pattern": [
    /^((c|o|u|js)-)?[a-z][a-z0-9]*(-[a-z0-9]+)*$/,
    { message: "Class names are lowercase-hyphen, without __element or --modifier (spec §7.1)" },
  ],
  "selector-disallowed-list": [/\.(is|has)-/],
};

