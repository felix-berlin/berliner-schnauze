// DTCG token files (tokens/*.tokens.json) → src/styles/tokens/_tokens.generated.scss.
// Spec: docs/superpowers/specs/2026-11-13-design-system-design.md §5. Usage: node scripts/build-tokens.mjs [--check]
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const OUT = new URL("src/styles/tokens/_tokens.generated.scss", root);
const HEADER = "// GENERATED by scripts/build-tokens.mjs — do not edit\n";
const ALIAS = /^\{([^}]+)\}$/;

/** Flattens a DTCG tree into Map<path, { type, value }>; `$type` is inherited from groups. */
const flatten = (tree, prefix = [], inherited, out = new Map()) => {
  const type = tree.$type ?? inherited;
  for (const [key, node] of Object.entries(tree)) {
    if (key.startsWith("$")) continue;
    const path = [...prefix, key];
    if (node === null || typeof node !== "object" || Array.isArray(node)) {
      throw new Error(`${path.join(".")}: neither a token nor a group`);
    }
    if ("$value" in node) {
      const t = node.$type ?? type;
      if (!t) throw new Error(`${path.join(".")}: no $type`);
      out.set(path.join("."), { type: t, value: node.$value });
    } else if (Object.keys(node).every((k) => k.startsWith("$"))) {
      throw new Error(`${path.join(".")}: group without tokens`);
    } else flatten(node, path, type, out);
  }
  return out;
};

const cssName = (path) => `--${path.replaceAll(".", "-")}`;
const num = (n) => String(Number(n.toFixed(6)));

const color = (c, path) => {
  if (c?.colorSpace !== "srgb") throw new Error(`${path}: colorSpace ${c?.colorSpace} (only srgb)`);
  const alpha = c.alpha ?? 1;
  const bytes = c.components.map((v) => v * 255);
  if (!bytes.every((b) => Math.abs(b - Math.round(b)) < 1e-3)) {
    return `color(srgb ${c.components.map(num).join(" ")}${alpha < 1 ? ` / ${num(alpha)}` : ""})`;
  }
  const [r, g, b] = bytes.map(Math.round);
  if (alpha < 1) return `rgb(${r} ${g} ${b} / ${num(alpha * 100)}%)`;
  return `#${[r, g, b].map((v) => v.toString(16).padStart(2, "0")).join("")}`;
};
const dim = (d) => (d.value === 0 ? "0" : `${num(d.value)}${d.unit}`);
const family = (f) =>
  Array.isArray(f) ? f.map((n) => (/\s/.test(n) ? `"${n}"` : n)).join(", ") : f;

/** Formats one value; aliases become var(). Shadows return layers [{ geometry, color }]. */
const format = (path, { type, value }, known) => {
  const ref = (v) => {
    const m = typeof v === "string" && v.match(ALIAS);
    if (!m) return undefined;
    if (!known.has(m[1])) throw new Error(`${path}: unknown alias ${v}`);
    return `var(${cssName(m[1])})`;
  };
  const alias = ref(value);
  if (alias) return alias;
  switch (type) {
    case "color":
      return color(value, path);
    case "dimension":
      return dim(value);
    case "duration": // a unitless 0 is invalid for <time>
      return `${num(value.value)}${value.unit}`;
    case "number":
    case "fontWeight":
      return String(value);
    case "fontFamily":
      return family(value);
    case "cubicBezier":
      return `cubic-bezier(${value.join(", ")})`;
    case "shadow":
      return [value].flat().map((s) => ({
        color: ref(s.color) ?? color(s.color, path),
        geometry: [s.inset ? "inset" : "", ...[s.offsetX, s.offsetY, s.blur, s.spread].map(dim)]
          .filter(Boolean)
          .join(" "),
      }));
    default:
      throw new Error(`${path}: unsupported $type ${type}`);
  }
};

const themed = (path, type, light, dark) => {
  const pair = (l, d) => (l === d ? l : `light-dark(${l}, ${d})`);
  if (type === "shadow" && Array.isArray(light) && Array.isArray(dark)) {
    if (light.length !== dark.length || light.some((l, i) => l.geometry !== dark[i].geometry)) {
      throw new Error(`${path}: geometry differs between themes`);
    }
    return light.map((l, i) => `${l.geometry} ${pair(l.color, dark[i].color)}`).join(", ");
  }
  const flat = (v) => (Array.isArray(v) ? v.map((s) => `${s.geometry} ${s.color}`).join(", ") : v);
  if (flat(light) !== flat(dark) && type !== "color") {
    throw new Error(`${path}: only colours and shadows may differ between themes`);
  }
  return pair(flat(light), flat(dark));
};

/** Throws on an alias cycle (a → b → a) inside one token map. */
const checkCycles = (tokens) => {
  for (const start of tokens.keys()) {
    const seen = new Set([start]);
    let next = tokens.get(start).value;
    while (typeof next === "string" && ALIAS.test(next)) {
      const target = next.match(ALIAS)[1];
      if (seen.has(target)) throw new Error(`${start}: alias cycle`);
      seen.add(target);
      next = tokens.get(target)?.value;
    }
  }
};

export default function buildTokens({ primitive, light, dark }) {
  const prim = flatten(primitive);
  const themes = { dark: flatten(dark), light: flatten(light) };
  for (const [name, own] of Object.entries(themes)) {
    const other = themes[name === "light" ? "dark" : "light"];
    for (const path of own.keys()) {
      if (!other.has(path))
        throw new Error(`${path}: missing in ${name === "light" ? "dark" : "light"}`);
      if (prim.has(path)) throw new Error(`${path}: defined in primitive and semantic`);
    }
  }
  const lines = [];
  for (const theme of [themes.light, themes.dark]) checkCycles(new Map([...prim, ...theme]));
  const knownLight = new Set([...prim.keys(), ...themes.light.keys()]);
  for (const [path, token] of prim) {
    const v = format(path, token, prim);
    lines.push([path, Array.isArray(v) ? v.map((s) => `${s.geometry} ${s.color}`).join(", ") : v]);
  }
  for (const [path, token] of themes.light) {
    const l = format(path, token, knownLight);
    const d = format(path, themes.dark.get(path), knownLight);
    lines.push([path, themed(path, token.type, l, d)]);
  }
  lines.sort(([a], [b]) => (a < b ? -1 : 1));
  const body = lines.map(([path, v]) => `    ${cssName(path)}: ${v};`).join("\n");
  return `${HEADER}@layer tokens {\n  :root {\n${body}\n  }\n}\n`;
}

export const readSources = () => {
  const read = (name) =>
    JSON.parse(readFileSync(new URL(`tokens/${name}.tokens.json`, root), "utf8"));
  return {
    dark: read("semantic.dark"),
    light: read("semantic.light"),
    primitive: read("primitive"),
  };
};

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const css = buildTokens(readSources());
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(OUT, "utf8");
    } catch (error) {
      if (error.code !== "ENOENT") throw error; // a missing file is just stale
    }
    if (current !== css) {
      console.error("src/styles/tokens/_tokens.generated.scss is stale: run pnpm tokens:build");
      process.exit(1);
    }
  } else writeFileSync(OUT, css);
}
